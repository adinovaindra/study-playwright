import { test, expect } from "@playwright/test";

test("login auto generated by codegen", async ({ page }) => {
  await page.goto(
    "https://opensource-demo.orangehrmlive.com/web/index.php/auth/login",
  );

  await page
    .getByRole("textbox", { name: "Username" })
    .pressSequentially("Admin", { delay: 200 });

  await page
    .getByRole("textbox", { name: "Password" })
    .pressSequentially("admin123", { delay: 200 });

  await page.getByRole("button", { name: "Login" }).click();

  await expect(
    page.locator("div").filter({ hasText: /^Dashboard$/ }),
  ).toBeVisible();

  await page
    .locator("i.oxd-icon.bi-caret-down-fill.oxd-userdropdown-icon")
    .click();

  await page.getByRole("menuitem", { name: "Logout" }).click();
  await expect(page.getByRole("heading", { name: "Login" })).toBeVisible();
});
